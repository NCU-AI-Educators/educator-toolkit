def _ceil_tenth(val: float) -> float:
    return math.ceil((val - 1e-9) * 10.0) / 10.0


def compute_budget_dict(
    target_width_in: float,
    fig_width_in: float,
    min_print_pt: float,
) -> dict[str, Any]:
    if target_width_in <= 0 or fig_width_in <= 0 or min_print_pt <= 0:
        raise ValueError("target_width_in, fig_width_in, and min_print_pt must all be > 0.")

    scale = target_width_in / fig_width_in
    strict_min_src_pt = _ceil_tenth(min_print_pt / scale)
    pad_factor = 1.03  # +3% margin against bbox_inches='tight' pad expansion

    tiers = {
        "min_fine_pt": max(strict_min_src_pt, _ceil_tenth((min_print_pt * pad_factor) / scale)),
        "body_pt": _ceil_tenth((max(min_print_pt + 0.5, 6.5) * pad_factor) / scale),
        "card_title_pt": _ceil_tenth((max(min_print_pt + 1.2, 7.2) * pad_factor) / scale),
        "panel_header_pt": _ceil_tenth((max(min_print_pt + 2.2, 8.2) * pad_factor) / scale),
        "panel_letter_pt": _ceil_tenth((max(min_print_pt + 4.5, 10.5) * pad_factor) / scale),
    }
    projected = {k: round(v * scale, 2) for k, v in tiers.items()}

    return {
        "target_width_in": round(target_width_in, 4),
        "fig_width_in": round(fig_width_in, 4),
        "min_print_pt": round(min_print_pt, 4),
        "scale": round(scale, 6),
        "strict_min_source_pt": strict_min_src_pt,
        "formula": "f_src >= f_print_min / (W_target / W_fig)",
        "recommended_source_fontsize_pt": tiers,
        "projected_print_fontsize_pt": projected,
        "venue_widths_in": VENUE_WIDTHS_IN,
    }


def write_json_and_exit(data: dict[str, Any], output_path: str | Path, *, ok: bool) -> None:
    out = Path(output_path).resolve()
    try:
        out.parent.mkdir(parents=True, exist_ok=True)
        with out.open("w", encoding="utf-8") as fh:
            json.dump(data, fh, indent=2, ensure_ascii=False)
            fh.write("\n")
    except OSError as exc:
        print(f"Error writing JSON output to {out}: {exc}", file=sys.stderr)
        sys.exit(1)

    status = "Success" if ok else "Failed"
    print(f"{status}! Report written to: {out}")
    sys.exit(0 if ok else 1)


# ---------------------------------------------------------------------------
# Subcommand 1: budget
# ---------------------------------------------------------------------------

def cmd_budget(args: argparse.Namespace) -> None:
    try:
        budget = compute_budget_dict(
            args.target_width_in,
            args.fig_width_in,
            args.min_print_pt,
        )
    except ValueError as exc:
        write_json_and_exit(
            {"ok": False, "command": "budget", "errors": [str(exc)]},
            args.output,
            ok=False,
        )
        return

    payload = {"ok": True, "command": "budget", **budget}
    write_json_and_exit(payload, args.output, ok=True)


