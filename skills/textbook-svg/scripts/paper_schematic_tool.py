def _parse_pdfinfo_page_size(stdout: str) -> tuple[float, float] | None:
    for line in stdout.splitlines():
        m = re.match(r"^Page size:\s*([0-9.]+)\s*x\s*([0-9.]+)\s*pts", line.strip())
        if m:
            return float(m.group(1)), float(m.group(2))
    return None


def _parse_pdffonts(stdout: str) -> list[dict[str, str]]:
    lines = [ln.rstrip("\r\n") for ln in stdout.splitlines() if ln.strip()]
    sep_idx = -1
    for idx, ln in enumerate(lines):
        if re.match(r"^-{4,}\s+-{4,}", ln):
            sep_idx = idx
            break
    if sep_idx == -1 or sep_idx + 1 >= len(lines):
        return []

    row_re = re.compile(
        r"^(\S+)\s+(.+?)\s+(\S+)\s+(yes|no)\s+(yes|no)\s+(yes|no)\s+(.+?)\s*$"
    )
    spans = [m.span() for m in re.finditer(r"-+", lines[sep_idx])]

    fonts: list[dict[str, str]] = []
    for ln in lines[sep_idx + 1 :]:
        m = row_re.match(ln)
        if m:
            fonts.append({
                "name": m.group(1),
                "type": m.group(2).strip(),
                "encoding": m.group(3),
                "emb": m.group(4),
                "sub": m.group(5),
                "uni": m.group(6),
                "object_id": m.group(7).strip(),
            })
        elif len(spans) >= 6:
            def _slice(col: int) -> str:
                s, e = spans[col]
                return ln[s:e].strip() if s < len(ln) else ""

            fonts.append({
                "name": _slice(0),
                "type": _slice(1),
                "encoding": _slice(2),
                "emb": _slice(3),
                "sub": _slice(4),
                "uni": _slice(5),
                "object_id": ln[spans[6][0] :].strip() if len(spans) > 6 and spans[6][0] < len(ln) else "",
            })
    return fonts


def _eval_numeric_expr(
    node: ast.AST,
    const_vars: dict[str, float],
    const_dicts: dict[str, dict[str, float]],
    shadowed: set[str],
) -> float | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, (int, float)) and not isinstance(node.value, bool):
        return float(node.value)
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.UAdd, ast.USub)):
        inner = _eval_numeric_expr(node.operand, const_vars, const_dicts, shadowed)
        if inner is not None:
            return inner if isinstance(node.op, ast.UAdd) else -inner
    if isinstance(node, ast.Name):
        if node.id not in shadowed and node.id in const_vars:
            return const_vars[node.id]
        return None
    if isinstance(node, ast.Subscript) and isinstance(node.value, ast.Name):
        dname = node.value.id
        if dname not in shadowed and dname in const_dicts:
            key_node = node.slice
            if isinstance(key_node, ast.Constant) and isinstance(key_node.value, str):
                return const_dicts[dname].get(key_node.value)
    if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Sub, ast.Mult, ast.Div)):
        left = _eval_numeric_expr(node.left, const_vars, const_dicts, shadowed)
        right = _eval_numeric_expr(node.right, const_vars, const_dicts, shadowed)
        if left is not None and right is not None:
            if isinstance(node.op, ast.Add):
                return left + right
            if isinstance(node.op, ast.Sub):
                return left - right
            if isinstance(node.op, ast.Mult):
                return left * right
            if isinstance(node.op, ast.Div) and abs(right) > 1e-12:
                return left / right
    return None


def _extract_dict_floats(
    node: ast.Dict,
    const_vars: dict[str, float],
    const_dicts: dict[str, dict[str, float]],
) -> dict[str, float] | None:
    out: dict[str, float] = {}
    for k, v in zip(node.keys, node.values):
        if isinstance(k, ast.Constant) and isinstance(k.value, str) and v is not None:
            fv = _eval_numeric_expr(v, const_vars, const_dicts, set())
            if fv is not None:
                out[k.value] = fv
    return out if out else None


def _audit_script_fontsizes(
    script_path: Path,
    scale: float,
    min_print_pt: float,
) -> dict[str, Any]:
    src = script_path.read_text(encoding="utf-8")
    tree = ast.parse(src, filename=str(script_path))

    const_vars: dict[str, float] = {}
    const_dicts: dict[str, dict[str, float]] = {}
    func_default_fontsize: dict[str, tuple[float, int]] = {}

    for stmt in tree.body:
        if isinstance(stmt, ast.Assign) and len(stmt.targets) == 1 and isinstance(stmt.targets[0], ast.Name):
            name = stmt.targets[0].id
            fv = _eval_numeric_expr(stmt.value, const_vars, const_dicts, set())
            if fv is not None:
                const_vars[name] = fv
            elif isinstance(stmt.value, ast.Dict):
                df = _extract_dict_floats(stmt.value, const_vars, const_dicts)
                if df:
                    const_dicts[name] = df
        elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name) and stmt.value is not None:
            name = stmt.target.id
            fv = _eval_numeric_expr(stmt.value, const_vars, const_dicts, set())
            if fv is not None:
                const_vars[name] = fv
            elif isinstance(stmt.value, ast.Dict):
                df = _extract_dict_floats(stmt.value, const_vars, const_dicts)
                if df:
                    const_dicts[name] = df
        elif isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)):
            pos_args = list(getattr(stmt.args, "posonlyargs", [])) + list(stmt.args.args)
            n_def = len(stmt.args.defaults)
            for arg_node, def_node in zip(pos_args[-n_def:] if n_def else [], stmt.args.defaults):
                if arg_node.arg == "fontsize" and def_node is not None:
                    fv = _eval_numeric_expr(def_node, const_vars, const_dicts, set())
                    if fv is not None:
                        func_default_fontsize[stmt.name] = (fv, arg_node.lineno)
            for kw_arg, kw_def in zip(stmt.args.kwonlyargs, stmt.args.kw_defaults):
                if kw_arg.arg == "fontsize" and kw_def is not None:
                    fv = _eval_numeric_expr(kw_def, const_vars, const_dicts, set())
                    if fv is not None:
                        func_default_fontsize[stmt.name] = (fv, kw_arg.lineno)

    checked: list[dict[str, Any]] = []
    violations: list[dict[str, Any]] = []
    unresolved_lines: list[int] = []
    min_req_src = round(min_print_pt / scale, 2)

    def _record(lineno: int, val: float, origin: str) -> None:
        print_pt = round(val * scale, 3)
        entry = {
            "line": lineno,
            "source_pt": round(val, 3),
            "projected_print_pt": print_pt,
            "origin": origin,
        }
        checked.append(entry)
        if val * scale + 1e-6 < min_print_pt:
            violations.append({
                **entry,
                "min_print_pt": min_print_pt,
                "min_required_source_pt": min_req_src,
            })

    def _walk(node: ast.AST, shadowed: set[str], local_consts: dict[str, float]) -> None:
        merged_consts = {**const_vars, **local_consts}
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            params = {
                a.arg
                for a in (
                    list(getattr(node.args, "posonlyargs", []))
                    + list(node.args.args)
                    + list(node.args.kwonlyargs)
                )
            }
            fn_locals: dict[str, float] = {}
            new_shadowed = set(shadowed) | params
            for body_stmt in node.body:
                if isinstance(body_stmt, ast.Assign) and len(body_stmt.targets) == 1 and isinstance(body_stmt.targets[0], ast.Name):
                    vname = body_stmt.targets[0].id
                    fv = _eval_numeric_expr(body_stmt.value, {**merged_consts, **fn_locals}, const_dicts, new_shadowed)
                    if fv is not None:
                        fn_locals[vname] = fv
                        new_shadowed.discard(vname)
                    else:
                        new_shadowed.add(vname)
                _walk(body_stmt, new_shadowed, fn_locals)
            return

        if isinstance(node, ast.Call):
            has_fontsize_kw = False
            for kw in node.keywords:
                if kw.arg == "fontsize":
                    has_fontsize_kw = True
                    fv = _eval_numeric_expr(kw.value, merged_consts, const_dicts, shadowed)
                    if fv is not None:
                        _record(kw.lineno, fv, "keyword_fontsize")
                    elif not (isinstance(kw.value, ast.Name) and kw.value.id in shadowed):
                        unresolved_lines.append(kw.lineno)
            if not has_fontsize_kw and isinstance(node.func, ast.Name) and node.func.id in func_default_fontsize:
                def_val, _ = func_default_fontsize[node.func.id]
                _record(node.lineno, def_val, f"default_fontsize({node.func.id})")

        for child in ast.iter_child_nodes(node):
            _walk(child, shadowed, local_consts)

    _walk(tree, set(), {})

    min_src = min((c["source_pt"] for c in checked), default=None)
    min_proj = min((c["projected_print_pt"] for c in checked), default=None)

    return {
        "script_path": str(script_path.resolve()),
        "checked_count": len(checked),
        "min_source_pt": min_src,
        "min_projected_print_pt": min_proj,
        "min_required_source_pt": min_req_src,
        "unresolved_fontsize_lines": sorted(set(unresolved_lines)),
        "violations": violations,
    }


def cmd_preflight(args: argparse.Namespace) -> None:
    errors: list[str] = []
    remediation: list[str] = []

    if args.target_width_in <= 0 or args.min_print_pt <= 0 or args.dpi <= 0:
        write_json_and_exit(
            {
                "ok": False,
                "command": "preflight",
                "errors": ["--target-width-in, --min-print-pt, and --dpi must all be > 0."],
            },
            args.output,
            ok=False,
        )
        return

    pdf_path = Path(args.pdf).resolve()
    if not pdf_path.is_file():
        write_json_and_exit(
            {
                "ok": False,
                "command": "preflight",
                "pdf_path": str(pdf_path),
                "errors": [f"PDF file not found: {pdf_path}"],
            },
            args.output,
            ok=False,
        )
        return

    missing_bins = [b for b in ("pdfinfo", "pdffonts", "pdftoppm") if shutil.which(b) is None]
    if missing_bins:
        write_json_and_exit(
            {
                "ok": False,
                "command": "preflight",
                "pdf_path": str(pdf_path),
                "missing_tools": missing_bins,
                "errors": [f"Missing required Poppler CLI utilities: {', '.join(missing_bins)}"],
                "remediation": [
                    "macOS: brew install poppler",
                    "Ubuntu/Debian: sudo apt-get update && sudo apt-get install -y poppler-utils",
                ],
            },
            args.output,
            ok=False,
        )
        return

    # 1. pdfinfo geometry check
    res_info = subprocess.run(["pdfinfo", str(pdf_path)], capture_output=True, text=True, check=False)
    if res_info.returncode != 0:
        write_json_and_exit(
            {
                "ok": False,
                "command": "preflight",
                "pdf_path": str(pdf_path),
                "errors": [f"pdfinfo failed: {res_info.stderr.strip()}"],
            },
            args.output,
            ok=False,
        )
        return

    page_pts = _parse_pdfinfo_page_size(res_info.stdout)
    if page_pts is None:
        write_json_and_exit(
            {
                "ok": False,
                "command": "preflight",
                "pdf_path": str(pdf_path),
                "errors": ["Could not parse `Page size: W x H pts` from pdfinfo output."],
            },
            args.output,
            ok=False,
        )
        return

    width_pts, height_pts = page_pts
    width_in = width_pts / 72.0
    height_in = height_pts / 72.0
    scale = args.target_width_in / width_in

    # 2. pdffonts vector embedding & Type 3 / 0-font checks
    res_fonts = subprocess.run(["pdffonts", str(pdf_path)], capture_output=True, text=True, check=False)
    if res_fonts.returncode != 0:
        errors.append(f"pdffonts failed: {res_fonts.stderr.strip()}")
        fonts: list[dict[str, str]] = []
    else:
        fonts = _parse_pdffonts(res_fonts.stdout)

    type3_fonts = [f["name"] for f in fonts if "type 3" in f["type"].lower()]
    unembedded_fonts = [f["name"] for f in fonts if f["emb"].lower() == "no"]

    if len(fonts) == 0:
        errors.append(
            "0 fonts detected in PDF (Ghostscript glyph-to-path outline or full rasterization trap; "
            "journal copy-editing requires selectable embedded TrueType/Type 42 text)."
        )
        remediation.append(
            'Export directly from Matplotlib with `plt.rcParams["pdf.fonttype"] = 42` and avoid Ghostscript `-dNoOutputFonts`.'
        )
    if type3_fonts:
        errors.append(f"Forbidden Type 3 bitmap/procedural font(s) detected: {type3_fonts}")
        remediation.append(
            'Set `plt.rcParams["pdf.fonttype"] = 42`, `plt.rcParams["ps.fonttype"] = 42`, and `plt.rcParams["mathtext.fontset"] = "dejavusans"`.'
        )
    if unembedded_fonts:
        errors.append(f"Unembedded font(s) (`emb == no`) detected: {unembedded_fonts}")
        remediation.append(
            'Set `plt.rcParams["pdf.fonttype"] = 42` and use locally installed sans-serif fonts (`Helvetica`, `Arial`, or `DejaVu Sans`).'
        )

    # 3. Optional AST source script font-size check
    script_audit: dict[str, Any] | None = None
    if args.script is not None:
        script_path = Path(args.script).resolve()
        if not script_path.is_file():
            errors.append(f"Provided --script file does not exist: {script_path}")
        else:
            try:
                script_audit = _audit_script_fontsizes(script_path, scale, args.min_print_pt)
                if script_audit["violations"]:
                    bad_lines = [
                        f"L{v['line']} ({v['source_pt']}pt -> {v['projected_print_pt']}pt < {args.min_print_pt}pt)"
                        for v in script_audit["violations"]
                    ]
                    errors.append(
                        f"Undersized source fontsize(s) at target width {args.target_width_in} in: "
                        + ", ".join(bad_lines)
                    )
                    remediation.append(
                        f"Increase flagged `fontsize=` values to >= {script_audit['min_required_source_pt']} pt "
                        f"(or narrow canvas width)."
                    )
            except SyntaxError as exc:
                errors.append(f"SyntaxError while parsing --script {script_path}: {exc}")

    # 4. pdftoppm PNG rasterization for mandatory visual inspection
    preview_dir = Path(args.preview_dir).resolve()
    preview_dir.mkdir(parents=True, exist_ok=True)
    stem = pdf_path.stem
    for old_png in preview_dir.glob(f"{stem}-*.png"):
        old_png.unlink(missing_ok=True)

    prefix = preview_dir / stem
    res_ppm = subprocess.run(
        ["pdftoppm", "-png", "-r", str(args.dpi), str(pdf_path), str(prefix)],
        capture_output=True,
        text=True,
        check=False,
    )
    preview_images: list[str] = []
    if res_ppm.returncode != 0:
        errors.append(f"pdftoppm failed: {res_ppm.stderr.strip()}")
    else:
        preview_images = [str(p.resolve()) for p in sorted(preview_dir.glob(f"{stem}-*.png"))]
        if not preview_images:
            errors.append(f"pdftoppm produced zero PNG files in {preview_dir}")

    ok = len(errors) == 0
    payload: dict[str, Any] = {
        "ok": ok,
        "command": "preflight",
        "pdf_path": str(pdf_path),
        "geometry": {
            "width_pts": round(width_pts, 3),
            "height_pts": round(height_pts, 3),
            "width_in": round(width_in, 4),
            "height_in": round(height_in, 4),
            "target_width_in": round(args.target_width_in, 4),
            "scale": round(scale, 6),
            "min_print_pt": round(args.min_print_pt, 4),
            "min_required_source_pt": round(args.min_print_pt / scale, 2),
        },
        "fonts": {
            "count": len(fonts),
            "type3_fonts": type3_fonts,
            "unembedded_fonts": unembedded_fonts,
            "items": fonts,
        },
        "script_fontsize_audit": script_audit,
        "preview_dpi": args.dpi,
        "preview_images": preview_images,
        "agent_visual_check_reminder": (
            "MANDATORY: Call `read_file` on EVERY image in `preview_images` to visually verify "
            "zero text-box collisions, clipped LaTeX subscripts, or unbridged wire crossings."
        ),
        "errors": errors,
        "remediation": remediation,
    }
    write_json_and_exit(payload, args.output, ok=ok)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Track C scientific paper schematic font budgeting, scaffolding, and PDF preflight CLI."
    )
    sub = parser.add_subparsers(dest="command", required=True)

    # budget
    p_budget = sub.add_parser(
        "budget",
        help="Compute reverse print-scale ratio and minimum source Matplotlib fontsize tiers.",
    )
    p_budget.add_argument("--target-width-in", type=float, required=True, help="Target figure width in paper (inches, e.g., 7.20 Nature double, 6.37 arXiv).")
    p_budget.add_argument("--fig-width-in", type=float, required=True, help="Matplotlib canvas width in inches (e.g., 14.0).")
    p_budget.add_argument("--min-print-pt", type=float, required=True, help="Minimum legible font size after print scaling (pt, typically 5.5–6.0).")
    p_budget.add_argument("--output", required=True, help="Output JSON file path.")

    # scaffold
    p_scaf = sub.add_parser(
        "scaffold",
        help="Generate a self-contained runnable Matplotlib schematic script (`dual-panel` or `multi-stage`).",
    )
    p_scaf.add_argument("--layout", choices=["dual-panel", "multi-stage"], required=True, help="Schematic composition layout.")
    p_scaf.add_argument("--target-width-in", type=float, required=True, help="Target figure width in paper (inches).")
    p_scaf.add_argument("--script-out", required=True, help="Destination `.py` script path.")
    p_scaf.add_argument("--output", required=True, help="Output receipt JSON file path.")
    p_scaf.add_argument("--fig-width-in", type=float, default=14.0, help="Canvas width in inches (default: 14.0).")
    p_scaf.add_argument("--fig-height-in", type=float, default=7.2, help="Canvas height in inches (default: 7.2).")
    p_scaf.add_argument("--min-print-pt", type=float, default=6.0, help="Minimum print font size in pt (default: 6.0).")

    # preflight
    p_pre = sub.add_parser(
        "preflight",
        help="Audit PDF geometry, embedded Type 42 fonts, AST source fontsizes, and render PNG previews.",
    )
    p_pre.add_argument("--pdf", required=True, help="Exported schematic PDF path.")
    p_pre.add_argument("--target-width-in", type=float, required=True, help="Target figure width in paper (inches).")
    p_pre.add_argument("--min-print-pt", type=float, required=True, help="Minimum allowed print font size (pt).")
    p_pre.add_argument("--preview-dir", required=True, help="Directory to write 200 DPI PNG rasterized preview(s).")
    p_pre.add_argument("--output", required=True, help="Output preflight report JSON file path.")
    p_pre.add_argument("--script", default=None, help="Optional `.py` Matplotlib script path for AST `fontsize=` verification.")
    p_pre.add_argument("--dpi", type=int, default=200, help="Preview rasterization DPI for `pdftoppm` (default: 200).")

    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()
    if args.command == "budget":
        cmd_budget(args)
    elif args.command == "scaffold":
        cmd_scaffold(args)
    elif args.command == "preflight":
        cmd_preflight(args)
    else:
        print(f"Unknown command: {args.command}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
